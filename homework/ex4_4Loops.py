# print numbers with the for loop

# from 0 to 9
for n in range(10):
    print(n, end=" ")
print()

# from 1 to 10
for n in range(1, 11):
    print(n, end=" ")
print()

# from 0 to 35 with step 5
for n in range(0, 36, 5):
    print(n, end=" ")
print()

# from 35 to 0 with step 5
for n in range(35, -1, -5):
    print(n, end=" ")
print()    