# print numbers with the while loop

# from 0 to 9
n = 0
while n <= 9:
    print(n, end=" ")
    n = n+1
print()

# from 1 to 10
n = 1
while n <= 10:
    print(n, end=" ")
    n = n+1
print()

# from 0 to 35 with step 5
n = 0
while n <= 35:
    print(n, end=" ")
    n = n+5
print()

# from 35 to 0 with step 5
n = 35
while n >= 0:
    print(n, end=" ")
    n = n-5
print()

